export function Icon({
  name,
  size = 16,
  className,
  color,
}: {
  name: string;
  size?: number;
  className?: string;
  color?: string;
}) {
  const C = ICONS[name] ?? Circle;
  return <C size={size} className={className} color={color} strokeWidth={1.9} />;
}

